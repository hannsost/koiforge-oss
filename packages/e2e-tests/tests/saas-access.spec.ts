import { expect, test } from '@playwright/test';

test('login gates the workspace, preserves the requested route, and logout revokes access', async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 812 });
  await page.goto('/#/agents');
  await expect(page.getByRole('heading', { name: 'Willkommen zurück' })).toBeVisible();
  await expect(page.getByRole('navigation', { name: 'Hauptnavigation' })).toHaveCount(0);
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: info.outputPath('koiforge-login-mobile.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.getByLabel('E-Mail', { exact: true }).fill('owner@example.test');
  await page.getByLabel('Passwort', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('nicht korrekt');
  await page.getByLabel('Passwort', { exact: true }).fill('browser fixture passphrase only');
  await page.getByRole('button', { name: 'Anmelden', exact: true }).click();
  await expect(page.locator('.nf-agent-page h1')).toHaveText('Agenten & KI');
  await expect(page.getByLabel('API-Schlüssel', { exact: false })).toHaveValue('');
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: info.outputPath('koiforge-agents-mobile.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: info.outputPath('koiforge-agents-desktop.png'), fullPage: true });
  await page.getByRole('link', { name: 'KI-Assistent öffnen' }).click();
  await expect(page.getByLabel('Nachricht', { exact: true })).toBeVisible();
  await page.getByLabel('Nachricht', { exact: true }).fill('Was lässt sich mit einer Datenquelle klären?');
  await page.getByRole('button', { name: 'Senden', exact: true }).click();
  await expect(page.locator('.nf-chat-message--assistant')).toBeVisible();
  await page.evaluate(() => { (document.activeElement as HTMLElement)?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: info.outputPath('koiforge-chat-desktop.png'), fullPage: true });
  await page.reload();
  await page.getByLabel('Deine Chats').selectOption({ label: 'Was lässt sich mit einer Datenquelle klären?' });
  await expect(page.locator('.nf-chat-message--user')).toContainText('Datenquelle');
  await page.getByRole('button', { name: 'Abmelden', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Willkommen zurück' })).toBeVisible();
  const response = await page.request.get('http://127.0.0.1:3191/api/aip/sessions');
  expect(response.status()).toBe(401);
});
